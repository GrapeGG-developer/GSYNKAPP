    /** Серия дней подряд. Считается по списку дат, поэтому не зависит от часового пояса. */
    fun streakFrom(dates: List<Long>, today: Long = LocalDate.now().toEpochDay()): Int {
        if (dates.isEmpty()) return 0
        val set = dates.toSortedSet(compareByDescending { it })
        var streak = 0
        var cursor = today
        while (set.contains(cursor)) {
            streak++
            cursor -= 1
        }
        // Один пропущенный день не рвёт серию: вчерашний визит тоже считается.
        if (streak == 0 && set.contains(today - 1)) {
            cursor = today - 1
            while (set.contains(cursor)) {
                streak++
                cursor -= 1
            }
        }
        return streak
    }

    fun daysBetween(a: Long, b: Long): Long = ChronoUnit.DAYS.between(LocalDate.ofEpochDay(a), LocalDate.ofEpochDay(b))

    /** Подарок за серию: что открылось сегодня. */
    fun rewardFor(streak: Int): String = when {
        streak >= 30 -> "тридцатка: полный набор эффектов и стёкол"
        streak >= 14 -> "две недели: секретная плитка «стекло живьём»"
        streak >= 7 -> "неделя: в рулетке появляются редкие функции"
        streak >= 3 -> "три дня: дополнительный цвет плиток"
        else -> "заходи подряд — на третий день откроется подарок"
    }

