/**
 * Рулетка: случайная функция из каталога. Выбор не повторяется дважды подряд,
 * а редкие плитки выпадают только тем, кто уже открыл пасхалки.
 */
object Roulette {

    private var lastIndex = -1

    /** Случайный маршрут из списка кандидатов с учётом редкости. */
    fun pick(candidates: List<String>, rare: List<String>, roll: Int): String {
        if (candidates.isEmpty()) return "page:surprise"
        val pool = if (roll % 5 == 4 && rare.isNotEmpty()) rare else candidates
        var index = roll % pool.size
        if (index == lastIndex && pool.size > 1) index = (index + 1) % pool.size
        lastIndex = index
        return pool[index]
    }
}
