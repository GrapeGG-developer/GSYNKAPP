    private const val PREFS = "gsynk_eggs"

    fun found(context: Context): Set<String> =
        context.getSharedPreferences(PREFS, Context.MODE_PRIVATE)
            .getStringSet("found", emptySet()) ?: emptySet()

    /** Открывает пасхалку. Возвращает true, если это случилось впервые. */
    fun unlock(context: Context, id: String): Boolean {
        val egg = byId(id) ?: return false
        val current = found(context)
        if (egg.id in current) return false
        context.getSharedPreferences(PREFS, Context.MODE_PRIVATE)
            .edit().putStringSet("found", current + egg.id).apply()
        return true
    }

    fun isFound(context: Context, id: String): Boolean = id in found(context)

    fun byId(id: String): Egg? = ALL.firstOrNull { it.id == id }

    fun progress(context: Context): Pair<Int, Int> = found(context).size to ALL.size

    fun reset(context: Context) {
        context.getSharedPreferences(PREFS, Context.MODE_PRIVATE).edit().clear().apply()
    }

    // ————— счётчик касаний значка —————
    fun taps(context: Context): Int =
        context.getSharedPreferences(PREFS, Context.MODE_PRIVATE).getInt("taps", 0)

    /** Возвращает новое число касаний и признак, что пасхалка только что открылась. */
    fun tapLogo(context: Context): Pair<Int, Boolean> {
        val next = taps(context) + 1
        context.getSharedPreferences(PREFS, Context.MODE_PRIVATE).edit().putInt("taps", next % 1000).apply()
        val opened = next % 7 == 0 && unlock(context, "logo7")
        return next to opened
    }
