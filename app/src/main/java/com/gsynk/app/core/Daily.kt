/**
 * Рулетка: случайная функция из каталога. Выбор не повторяется дважды подряд,
 * а редкие плитки выпадают только тем, кто уже открыл пасхалки.
 */
object Roulette {

    private var lastIndex = -1

    /** Случайный маршрут из списка кандидатов с учётом редкости. */
    fun pick(candidates: List<String>, rare: List<String>, roll: Int): String {
        if (candidates.isEmpty()) return "page:surprise"
        val pool = if (roll % 5 == 4 && rare.isNotEmpty()) rare else candidates
        var index = roll % pool.size
        if (index == lastIndex && pool.size > 1) index = (index + 1) % pool.size
        lastIndex = index
        return pool[index]
    }
}


/**
 * «Телефон лицом вниз» — простая проверка для пасхалки «переворот».
 *
 * Живёт в core, потому что это чистая работа с датчиком: подписка на гравитацию,
 * сравнение с порогом и выключение, когда экран закрыли. Системные AON-датчики
 * пропускаются тем же фильтром, что и в лаборатории: иначе Android 16 роняет процесс.
 */
object EverydayFaceDown {

    /** Порог: при экране вниз гравитация по Z уходит ниже −8 м/с². */
    const val THRESHOLD = -8f

    fun isFaceDown(z: Float): Boolean = z <= THRESHOLD

    /**
     * Подписка на гравитацию. Возвращает функцию отписки: вызывать её обязательно,
     * иначе датчик продолжит будить телефон без пользы.
     */
    fun watch(context: android.content.Context, onFlipped: (Boolean) -> Unit): () -> Unit {
        val manager = context.getSystemService(android.content.Context.SENSOR_SERVICE)
            as? android.hardware.SensorManager ?: return {}
        val sensor = manager.getDefaultSensor(android.hardware.Sensor.TYPE_GRAVITY)
            ?.takeIf { candidate ->
                !DeviceLab.isSystemOnlySensor(
                    android.hardware.Sensor.TYPE_GRAVITY,
                    candidate.name,
                    candidate.stringType
                )
            } ?: return {}
        var reported = false
        val listener = object : android.hardware.SensorEventListener {
            override fun onSensorChanged(event: android.hardware.SensorEvent) {
                val down = isFaceDown(event.values.getOrNull(2) ?: 0f)
                if (down && !reported) {
                    reported = true
                    runCatching { Eggs.unlock(context, "flip") }
                    onFlipped(true)
                } else if (!down) {
                    reported = false
                }
            }

            override fun onAccuracyChanged(sensor: android.hardware.Sensor?, accuracy: Int) = Unit
        }
        runCatching { manager.registerListener(listener, sensor, android.hardware.SensorManager.SENSOR_DELAY_UI) }
        return { runCatching { manager.unregisterListener(listener) } }
    }
}
