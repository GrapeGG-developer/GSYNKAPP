    /** Набор дня: чистая функция от даты, поэтому проверяется тестом. */
    fun forDate(date: LocalDate = LocalDate.now()): Day {
        val epoch = date.toEpochDay()
        val rnd = Lcg(epoch * 2_654_435_761L + 17L)
        val fact = facts[rnd.next(facts.size)]
        val task = tasks[rnd.next(tasks.size)]
        val joke = jokes[rnd.next(jokes.size)]
        val sticker = rnd.next(stickers.size).toLong()
        val tone = rnd.next(MetroTones)
        return Day(
            epochDay = epoch,
            sticker = sticker,
            title = stickers[sticker.toInt()],
            fact = fact,
            task = task,
            joke = joke,
            number = 100 + rnd.next(900),
            tone = tone,
            word = words[rnd.next(words.size)]
        )
    }

    /** Сколько разных плиток палитры разрешено дню: у нас двадцать цветов Metro. */
    const val MetroTones = 20

    /** Серия дней подряд. Считается по списку дат, поэтому не зависит от часового пояса. */
    fun streakFrom(dates: List<Long>, today: Long = LocalDate.now().toEpochDay()): Int {
        if (dates.isEmpty()) return 0
        val set = dates.toSortedSet(compareByDescending { it })
        var streak = 0
        var cursor = today
        while (set.contains(cursor)) {
            streak++
            cursor -= 1
        }
        // Один пропущенный день не рвёт серию: вчерашний визит тоже считается.
        if (streak == 0 && set.contains(today - 1)) {
            cursor = today - 1
            while (set.contains(cursor)) {
                streak++
                cursor -= 1
            }
        }
        return streak
    }

    fun daysBetween(a: Long, b: Long): Long = ChronoUnit.DAYS.between(LocalDate.ofEpochDay(a), LocalDate.ofEpochDay(b))

    /** Подарок за серию: что открылось сегодня. */
    fun rewardFor(streak: Int): String = when {
        streak >= 30 -> "тридцатка: полный набор эффектов и стёкол"
        streak >= 14 -> "две недели: секретная плитка «стекло живьём»"
        streak >= 7 -> "неделя: в рулетке появляются редкие функции"
        streak >= 3 -> "три дня: дополнительный цвет плиток"
        else -> "заходи подряд — на третий день откроется подарок"
    }

    // ————— визиты —————
    private const val PREFS = "gsynk_daily"

    fun visits(context: Context): List<Long> =
        (context.getSharedPreferences(PREFS, Context.MODE_PRIVATE).getString("visits", "") ?: "")
            .split('|').mapNotNull { it.toLongOrNull() }

    fun markVisit(context: Context, today: Long = LocalDate.now().toEpochDay()): Int {
        val list = (visits(context).filter { it != today } + today).takeLast(60)
        context.getSharedPreferences(PREFS, Context.MODE_PRIVATE)
            .edit().putString("visits", list.joinToString("|")).apply()
        return streakFrom(list, today)
    }

    fun openedDays(context: Context): Int = visits(context).distinct().size

    fun giftTaken(context: Context, today: Long = LocalDate.now().toEpochDay()): Boolean =
        context.getSharedPreferences(PREFS, Context.MODE_PRIVATE).getLong("gift", 0L) == today

    fun takeGift(context: Context, today: Long = LocalDate.now().toEpochDay()) {
        context.getSharedPreferences(PREFS, Context.MODE_PRIVATE).edit().putLong("gift", today).apply()
    }

    /** Простой линейный конгруэнтный генератор: одинаковый вход — одинаковый выход. */
    class Lcg(seed: Long) {
        private var state: Long = if (seed == 0L) 8_812_621L else seed

        fun next(bound: Int): Int {
            state = state * 6_364_136_223_846_793_005L + 1_442_695_040_888_963_407L
            val value = (state ushr 33).toInt()
            return ((value % bound) + bound) % bound
        }
    }
